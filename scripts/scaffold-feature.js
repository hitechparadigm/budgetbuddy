/**
 * Scaffolds the frontend API service and page files for <name>.
 * Aborts with no writes if any target path already exists.
 * @param {string} name - kebab-case feature name
 * @returns {string[]} the list of file paths written
 */
function scaffoldFrontend(name) {
  const targets = frontendTargets(name);
  const checkPaths = [targets.apiService, targets.page];

  fs.writeFileSync(targets.apiService, apiServiceTemplate(name));
  fs.writeFileSync(targets.page, pageTemplate(name));

  return checkPaths;
}

/**
 * Scaffolds both the backend Lambda files and frontend service+page files for
 * <name>. Checks every target path across both halves before writing
 * anything - if any single path already exists, aborts and writes nothing.
 * @param {string} name - kebab-case feature name
 * @returns {string[]} the list of file paths written, backend then frontend
 */
function scaffoldFeature(name) {
  const backend = backendTargets(name);
  const frontend = frontendTargets(name);
  const allPaths = [
    backend.indexJs,
    backend.serviceJs,
    backend.repositoryJs,
    backend.testJs,
    backend.packageJson,
    backend.todoMd,
    frontend.apiService,
    frontend.page,
  ];

  const conflicts = allPaths.filter((p) => fs.existsSync(p));
  if (conflicts.length) {
    throw new Error(`Refusing to overwrite existing file(s):\n  ${conflicts.join('\n  ')}`);
  }

  const written = [...scaffoldBackend(name), ...scaffoldFrontend(name)];
  return written;
}

function main() {
  const name = process.argv[2];
  if (!name) {
    console.error('\u274c Usage: node scripts/scaffold-feature.js <name>');
    process.exit(1);
  }
  if (!/^[a-z][a-z0-9-]*$/.test(name)) {
    console.error(`\u274c Invalid name "${name}" - must be kebab-case (lowercase letters, digits, hyphens)`);
    process.exit(1);
  }

  try {
    const written = scaffoldFeature(name);
    console.log(`\u2705 Scaffolded ${name}:`);
    for (const p of written) {
      console.log(`   ${path.relative(ROOT, p)}`);
    }
  } catch (error) {
    console.error(`\u274c ${error.message}`);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = { toPascalCase, scaffoldBackend, scaffoldFrontend, scaffoldFeature, backendTargets, frontendTargets };